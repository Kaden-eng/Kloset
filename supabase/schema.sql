-- Indexes for performance optimization

-- Profiles indexes
create index if not exists profiles_email_idx on profiles(email);
create index if not exists profiles_username_idx on profiles(username);
create index if not exists profiles_created_at_idx on profiles(created_at);

-- Inventory items indexes
create index if not exists inventory_items_user_id_idx on inventory_items(user_id);
create index if not exists inventory_items_status_idx on inventory_items(status);
create index if not exists inventory_items_category_idx on inventory_items(category);
create index if not exists inventory_items_brand_idx on inventory_items(brand);
create index if not exists inventory_items_created_at_idx on inventory_items(created_at);
create index if not exists inventory_items_user_status_idx on inventory_items(user_id, status);
create index if not exists inventory_items_user_category_idx on inventory_items(user_id, category);

-- Marketplace analytics indexes
create index if not exists marketplace_analytics_inventory_item_id_idx on marketplace_analytics(inventory_item_id);
create index if not exists marketplace_analytics_platform_idx on marketplace_analytics(platform);
create index if not exists marketplace_analytics_created_at_idx on marketplace_analytics(created_at);
create index if not exists marketplace_analytics_item_platform_idx on marketplace_analytics(inventory_item_id, platform);

-- Saved analyses indexes
create index if not exists saved_analyses_user_id_idx on saved_analyses(user_id);
create index if not exists saved_analyses_created_at_idx on saved_analyses(created_at);

-- Enable realtime for tables that benefit from real-time updates
alter publication supabase_realtime add table inventory_items;
alter publication supabase_realtime add table marketplace_analytics;
alter publication supabase_realtime add table saved_analyses;

